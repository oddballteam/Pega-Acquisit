#!/usr/bin/env python3
"""Regenerate inventory/ and schema/ from the Pega export zip in export/.

Usage (from the repo root):  python3 scripts/extract.py

Only the standard library is used. The export's rule payloads (instances_NNNNN.bin
inside *_rules.jar) are Pega's own binary format and are not decoded. This script reads
the two plain-text parts of the export:
  - *_rules.jar  META-INF/contents.txt : one line per rule instance
  - *_schema.jar *.xml                 : database table definitions
"""
import csv
import io
import re
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPORT_DIR = ROOT / "export"
INV = ROOT / "inventory"
SCHEMA = ROOT / "schema"

# Rule types that record version history or tagging rather than application logic.
NOISE_TYPES = {"HISTORY-RULE", "DATA-TAG-RELEVANTRECORD"}


def find_export():
    zips = sorted(EXPORT_DIR.glob("*.zip"))
    if len(zips) != 1:
        sys.exit(f"expected exactly one .zip in {EXPORT_DIR}, found {len(zips)}")
    return zips[0]


def inner_jar(outer, suffix):
    name = next((n for n in outer.namelist() if n.endswith(suffix)), None)
    if not name:
        sys.exit(f"no *{suffix} inside the export")
    return zipfile.ZipFile(io.BytesIO(outer.read(name)))


def parse_key(key):
    """'RULE-OBJ-FLOW MYORG-ACQUISIT-WORK-X CLOSURE_FLOW #20260825T215511.805 GMT'
    -> type, applies_to, name, saved_at."""
    saved_at = ""
    m = re.search(r" #(\S+ GMT)$", key)
    if m:
        saved_at = m.group(1)
        key = key[: m.start()]
    parts = key.split(" ")
    rule_type = parts[0]
    rest = parts[1:]
    if len(rest) >= 2:
        applies_to, name = rest[0], " ".join(rest[1:])
    else:
        applies_to, name = "", " ".join(rest)
    return rule_type, applies_to, name, saved_at


def main():
    export = find_export()
    outer = zipfile.ZipFile(export)

    rules_jar = inner_jar(outer, "_rules.jar")
    contents = rules_jar.read("META-INF/contents.txt").decode("utf-8")
    lines = [ln for ln in contents.splitlines() if ln.strip()][1:]  # drop header row

    INV.mkdir(exist_ok=True)
    (INV / "contents.txt").write_text(contents, encoding="utf-8")

    header = ["rule_type", "applies_to", "name", "ruleset", "ruleset_version",
              "available", "last_updated", "saved_at", "owning_file", "instance_key"]
    rows = []
    for ln in lines:
        key, ruleset_ver, avail, updated, owning = ln.split("*")
        rule_type, applies_to, name, saved_at = parse_key(key)
        ruleset, _, version = ruleset_ver.partition(":")
        rows.append([rule_type, applies_to, name, ruleset, version, avail,
                     updated, saved_at, owning, key])
    rows.sort(key=lambda r: (r[0], r[1], r[2]))

    def write_csv(path, data):
        with open(path, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(header)
            w.writerows(data)

    write_csv(INV / "rules-all.csv", rows)
    logic = [r for r in rows if r[0] not in NOISE_TYPES]
    write_csv(INV / "rules.csv", logic)

    by_type = defaultdict(list)
    for r in logic:
        by_type[r[0]].append(r)
    out_dir = INV / "by-type"
    out_dir.mkdir(exist_ok=True)
    for old in out_dir.glob("*.csv"):
        old.unlink()
    for rule_type, data in by_type.items():
        write_csv(out_dir / f"{rule_type}.csv", data)

    # Case types are the classes under the work layer.
    case_types = sorted({r[1] for r in logic
                         if re.match(r"MYORG-ACQUISIT-WORK-[A-Z0-9]+$", r[1])})
    data_types = sorted({r[1] for r in logic
                         if re.match(r"MYORG-ACQUISIT-DATA-[A-Z0-9]+$", r[1])})
    flows = defaultdict(list)
    for r in by_type.get("RULE-OBJ-FLOW", []):
        flows[r[1]].append(r[2])

    counts = Counter(r[0] for r in rows)
    with open(INV / "SUMMARY.md", "w", encoding="utf-8") as f:
        f.write(f"# Acquisit rule inventory\n\nGenerated by `scripts/extract.py` from `export/{export.name}`.\n\n")
        f.write(f"- Rule instances in the export: **{len(rows):,}**\n")
        f.write(f"- Excluding version history and tags ({', '.join(sorted(NOISE_TYPES))}): **{len(logic):,}** (`rules.csv`)\n\n")
        f.write(f"## Case types ({len(case_types)})\n\n")
        for c in case_types:
            names = sorted(set(flows.get(c, [])))
            f.write(f"- `{c}`" + (f" — flows: {', '.join(names)}" if names else "") + "\n")
        f.write(f"\n## Data types ({len(data_types)})\n\n")
        for d in data_types:
            f.write(f"- `{d}`\n")
        f.write("\n## Rule types\n\n| Rule type | Count |\n|---|---:|\n")
        for t, n in counts.most_common():
            f.write(f"| {t} | {n:,} |\n")

    schema_jar = inner_jar(outer, "_schema.jar")
    SCHEMA.mkdir(exist_ok=True)
    for old in SCHEMA.glob("*.xml"):
        old.unlink()
    for n in schema_jar.namelist():
        if n.endswith(".xml") or n.endswith(".properties"):
            target = SCHEMA / Path(n).name
            target.write_bytes(schema_jar.read(n))

    print(f"{len(rows)} rules, {len(logic)} logic rules, {len(by_type)} types, "
          f"{len(case_types)} case types, {len(data_types)} data types")


if __name__ == "__main__":
    main()
